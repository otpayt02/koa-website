#!/usr/bin/env node
/**
 * seed-dictionary.mjs — deterministic importer: karen_dict_full.json →
 * scripts/seed/dictionary_import.sql
 *
 * Everything lands as source='scraped', status='pending'. Nothing becomes
 * canonical until a reviewer approves it (koa cross-project rule).
 *
 * Deterministic: entry/translation ids are content hashes, so re-running the
 * script produces byte-identical output and the SQL is re-runnable with
 * INSERT OR IGNORE.
 *
 * Usage: node scripts/seed-dictionary.mjs [--source PATH]
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const sourceArgIdx = process.argv.indexOf("--source");
const SOURCE = sourceArgIdx !== -1
  ? process.argv[sourceArgIdx + 1]
  : "C:/Users/olive/Projects/karen-lang-trans/karen_dict_full.json";
const OUT = join(__dirname, "seed", "dictionary_import.sql");
// Drizzle-migration format of the same statements (statement-breakpoint
// separated, no BEGIN/COMMIT — the hosting control plane applies each one).
const MIGRATION_OUT = join(__dirname, "..", "drizzle", "0003_dictionary_seed.sql");

const raw = readFileSync(SOURCE, "utf-8");
const entries = JSON.parse(raw);
if (!Array.isArray(entries)) throw new Error("Expected a JSON array");

function esc(s) {
  return String(s).replace(/'/g, "''");
}
function shaId(prefix, ...parts) {
  const h = createHash("sha1").update(parts.join("|")).digest("hex").slice(0, 16);
  return `${prefix}_${h}`;
}
function normalize(word) {
  return String(word).normalize("NFC").trim().toLowerCase();
}

const seen = new Set();
const lines = [
  "-- Generated by scripts/seed-dictionary.mjs — DO NOT EDIT BY HAND",
  `-- Source: ${SOURCE}`,
  `-- Generated at (run marker stripped for determinism): deterministic content-hash ids`,
  "BEGIN TRANSACTION;",
];
// Statements only (no transaction wrappers) — reused for the drizzle
// migration format, which separates statements with --> statement-breakpoint.
const stmts = [];

let entryCount = 0;
let translationCount = 0;
let skippedDupes = 0;

for (const e of entries) {
  const karen = String(e.karen ?? "").normalize("NFC").trim();
  if (!karen) continue;
  const defs = Array.isArray(e.definitions) ? e.definitions : [];
  const page = e.page != null ? Number(e.page) : null;

  const dedupeKey = `${karen}|${page}|${defs.join("¶")}`;
  if (seen.has(dedupeKey)) {
    skippedDupes++;
    continue;
  }
  seen.add(dedupeKey);

  const entryId = shaId("ent", karen, String(page), defs.join("¶"));
  stmts.push(
    `INSERT OR IGNORE INTO dictionary_entries (id, word, normalized_word, part_of_speech, category, etymology, source, provenance_url, provenance_scraped_at, provenance_content_hash, provenance_raw_content, status, version, created_by, reviewed_by, review_note, reviewed_at, created_at, updated_at) ` +
      `VALUES ('${entryId}', '${esc(karen)}', '${esc(normalize(karen))}', NULL, NULL, NULL, 'scraped', 'karen-lang-trans/karen_dict_full.json', NULL, NULL, '${esc(JSON.stringify(e))}', 'pending', 1, NULL, NULL, NULL, NULL, (unixepoch() * 1000), (unixepoch() * 1000));`
  );
  entryCount++;

  for (const def of defs) {
    const text = String(def ?? "").normalize("NFC").trim();
    if (!text) continue;
    const trnId = shaId("trn", entryId, text);
    stmts.push(
      `INSERT OR IGNORE INTO dictionary_translations (id, entry_id, language, text, context, dialect, contributor_id, reviewer_id, status, created_at, updated_at) ` +
        `VALUES ('${trnId}', '${entryId}', 'en', '${esc(text)}', NULL, NULL, NULL, NULL, 'pending', (unixepoch() * 1000), (unixepoch() * 1000));`
    );
    translationCount++;
  }
}

lines.push(...stmts, "COMMIT;");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n", "utf-8");
// Drizzle migration format: same statements, breakpoint-separated, no BEGIN/COMMIT.
writeFileSync(MIGRATION_OUT, stmts.join("\n--> statement-breakpoint\n") + "\n", "utf-8");

console.log(JSON.stringify({
  sourceEntries: entries.length,
  dictionaryEntries: entryCount,
  translations: translationCount,
  skippedDuplicates: skippedDupes,
  outFile: OUT,
  migrationFile: MIGRATION_OUT,
}, null, 2));
